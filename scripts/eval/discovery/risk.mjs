/**
 * @param {{repository:string, baseCommit:string, candidateCommit:string, spec?:any, existingTests?:string[]}} opts
 * @returns {object} atd.change-risk/v1 report
 */
export function analyzeChange(opts) {
  if (!opts || typeof opts !== 'object') throw new DiscoveryError('usage', 'analyzeChange requires an options object');
  const { repository, spec = null, existingTests } = opts;
  const baseCommit = resolveCommit(repository, opts.baseCommit, 'baseCommit');
  const candidateCommit = resolveCommit(repository, opts.candidateCommit, 'candidateCommit');
  const specData = loadSpec(spec);

  const diffArgs = [baseCommit, candidateCommit, '--'];
  const diffBytes = git(repository, ['diff', ...DIFF_FLAGS, '--binary', '--full-index', ...diffArgs]);
  const raw = parseRawDiff(git(repository, ['diff', '--raw', '-z', '--no-abbrev', ...DIFF_FLAGS, ...diffArgs]));
  const binary = binaryFiles(git(repository, ['diff', '--numstat', '-z', ...DIFF_FLAGS, ...diffArgs]));
  raw.sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : 0));

  const skipped = [];
  const targets = [];
  for (const entry of raw) {
    const reason = skipReasonForPath(entry, binary);
    if (reason) { skipped.push({ file: entry.file, reason }); continue; }
    if (entry.oldSha === entry.newSha) { skipped.push({ file: entry.file, reason: 'formatting_only' }); continue; }
    const candBlob = readBlob(repository, candidateCommit, entry.file);
    if (!candBlob) { skipped.push({ file: entry.file, reason: 'deleted' }); continue; }
    if (candBlob.length > MAX_SOURCE_BYTES) { skipped.push({ file: entry.file, reason: 'non_source' }); continue; }
    if (candBlob.includes(0)) { skipped.push({ file: entry.file, reason: 'binary' }); continue; }
    const candText = candBlob.toString('utf8');
    if (hasGeneratedHeader(candText)) { skipped.push({ file: entry.file, reason: 'generated' }); continue; }
    let baseText = '';
    if (entry.status !== 'A') {
      const baseBlob = readBlob(repository, baseCommit, entry.file);
      if (baseBlob) {
        if (baseBlob.length > MAX_SOURCE_BYTES || baseBlob.includes(0)) { skipped.push({ file: entry.file, reason: 'non_source' }); continue; }
        baseText = baseBlob.toString('utf8');
      }
    }
    if (candText.trim() === '') { skipped.push({ file: entry.file, reason: 'deleted' }); continue; }
    const target = analyzeFile({ repository, baseCommit, candidateCommit, entry, baseText, candText });
    if (!target) skipped.push({ file: entry.file, reason: 'formatting_only' });
    else targets.push(target);
  }

  const tests = findAffectedTests({ repository, candidateCommit, targetFiles: targets.map((t) => t.file), existingTests });
  for (const t of targets) t.affectedTests = tests.get(t.file) || [];

  skipped.sort((a, b) => (a.file < b.file ? -1 : a.file > b.file ? 1 : 0));
  const report = {
    schema: 'atd.change-risk/v1',
    baseCommit,
    candidateCommit,
    diffSha256: sha256(diffBytes),
    specSha256: specData ? specData.sha256 : null,
    ruleset: { ...RULESET },
    llmAssist: { used: false },
    targets,
    skipped,
  };
  const problems = validateSchema(loadSchema('atd.change-risk.v1.json'), report);
  if (problems.length > 0) throw new DiscoveryError('invalid_report', `internal: report violates schema: ${problems[0].path} ${problems[0].message}`);
  return report;
}

/** Structural validation for a report received from elsewhere (e.g. read from disk). */
export function validateChangeRisk(report) {
  const errors = validateSchema(loadSchema('atd.change-risk.v1.json'), report);
  if (errors.length === 0 && !(isSha1(report.baseCommit) && isSha1(report.candidateCommit))) errors.push({ path: '$', message: 'commits must be full SHAs' });
  return errors;
}

