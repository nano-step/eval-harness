const HELP = `Usage: risk.mjs --repo=PATH --base=REV --candidate=REV [--spec=FILE] [--tests=a,b] --out=FILE

Deterministic diff-based change-risk analysis (atd.change-risk/v1).
  --repo=PATH       git repository (read-only; never modified or executed)
  --base=REV        base revision (resolved to a full SHA)
  --candidate=REV   candidate revision (resolved to a full SHA)
  --spec=FILE       task specification; only its SHA-256 is recorded
  --tests=LIST      comma-separated repository-relative existing test files
                    (default: tests discovered in the candidate tree)
  --out=FILE        write the report here (default: stdout)
Formatting-only, comment-only, generated, dependency, lockfile, deleted, binary and non-source
changes yield no targets; each is listed in "skipped" with a reason. Literal (string, template,
regex) changes are meaningful. Suspected failure modes are hypotheses, never findings.
Exit: 0 ok, 1 failure, 2 usage.
`;

export async function main(argv) {
  const { flags } = parseFlags(argv);
  if (flags.help) { process.stdout.write(HELP); return 0; }
  requireFlags(flags, ['repo', 'base', 'candidate']);
  const report = analyzeChange({
    repository: flags.repo,
    baseCommit: flags.base,
    candidateCommit: flags.candidate,
    spec: flags.spec || null,
    existingTests: flags.tests ? flags.tests.split(',').filter(Boolean) : undefined,
  });
  if (flags.out) writeJsonFile(flags.out, report);
  else process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
  return 0;
}

if (isMain(import.meta.url)) await runCli(main);
