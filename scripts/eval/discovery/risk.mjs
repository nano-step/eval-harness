#!/usr/bin/env node
// Deterministic diff-based change-risk analysis (atd.change-risk/v1).
// Reads two git revisions, never executes repository code, never modifies the repository, and
// makes no model calls. Suspected failure modes are HYPOTHESES, never findings.
import path from 'node:path';
import {
  DiscoveryError, canonicalSha256, git, isSha1, isTestPath, loadSchema, loadSpec, parseFlags, readBlob,
  requireFlags, resolveCommit, runCli, sha256, sourceExtension, validateSchema, writeJsonFile,
  isMain,
} from './generation-util.mjs';
import {
  comparableTokens, diffKeys, extractSymbols, lex, moduleSpecifiers,
} from './generation-lexer.mjs';

const MAX_SOURCE_BYTES = 2 * 1024 * 1024;
const MAX_TEST_BYTES = 512 * 1024;
const MAX_HUNKS_PER_FILE = 200;
const MAX_BEHAVIORS_PER_FILE = 20;
const MAX_TEST_FILES = 2000;
const MAX_EXISTING_TESTS = 5000;

const DEPENDENCY_DIRS = new Set(['node_modules', 'dist', 'build', 'vendor']);
const LOCKFILES = new Set([
  'package-lock.json', 'npm-shrinkwrap.json', 'yarn.lock', 'pnpm-lock.yaml', 'bun.lockb', 'bun.lock',
  'composer.lock', 'Cargo.lock', 'Gemfile.lock', 'poetry.lock', 'Pipfile.lock', 'go.sum',
]);
const GENERATED_HEADER_RE = /@generated|\bDO NOT EDIT\b|\bgenerated by\b|\bauto-?generated\b|\bcode generated\b|\bthis file (?:was|is) (?:automatically |auto-?)?generated\b/i;
const GENERATED_NAME_RE = /(?:^|\/)__generated__\/|\.generated\.[A-Za-z]+$|\.gen\.[A-Za-z]+$|\.min\.[cm]?js$|\.d\.[cm]?ts$/;
const CONFIG_NAME_RE = /(?:^|\/)[^/]*\.config\.[cm]?[jt]s$/;

// ---------------------------------------------------------------------------
// Rules. The descriptor below is hashed into report.ruleset.sha256 so a rules change is visible.
// ---------------------------------------------------------------------------
const WEIGHTS = {
  authz: 3, boundary: 3, math_spatial: 2, error_path: 2, async: 2, validation: 2, state: 2,
  conditional: 2, api_contract: 2, string_literal: 1, data_literal: 1, logic_change: 1,
};
const RELATIONAL = new Set(['<', '<=', '>', '>=']);
const CONDITIONAL_KEYWORDS = new Set(['if', 'else', 'switch', 'case', 'while', 'for', 'do']);
const CONDITIONAL_OPS = new Set(['?', '&&', '||', '??', '!', '==', '!=', '===', '!==', '<', '<=', '>', '>=', '&&=', '||=', '??=']);
const ASYNC_IDS = new Set(['async', 'await', 'Promise', 'then', 'setTimeout', 'setInterval', 'yield', 'queueMicrotask', 'resolve', 'reject', 'AbortController', 'signal']);
const ERROR_CHANGED_RE = /(?:^|\.)(?:Error|TypeError|RangeError|SyntaxError|AggregateError)$|^(?:reject|Error|TypeError|RangeError)$/;
const ERROR_CONTEXT_IDS = new Set(['throw', 'try', 'catch', 'finally', 'reject']);
const STATE_IDS = new Set(['push', 'pop', 'shift', 'unshift', 'splice', 'set', 'delete', 'add', 'clear', 'assign', 'setState', 'dispatch', 'emit', 'cache', 'state', 'store']);
const ASSIGN_OPS = new Set(['=', '+=', '-=', '*=', '/=', '%=', '**=', '&&=', '||=', '??=', '<<=', '>>=', '>>>=', '&=', '|=', '^=']);
const AUTHZ_RE = /auth|permission|role|admin|acl|token|session|owner|privilege|grant|deny|forbid|allow|csrf|secret|credential|password/i;
const VALIDATION_RE = /valid|sanit|schema|assert|parse|check|isNaN|isFinite|isInteger|typeof|instanceof|^is[A-Z]/;
const MATH_RE = /^(?:x|y|z|w|h|dx|dy|left|right|top|bottom|width|height|overlap\w*|intersect\w*|collid\w*|collision\w*|rect\w*|bounds?\w*|area|distance|dist|angle|radius|vector\w*|matrix|point|pos\w*|min|max|abs|sqrt|floor|ceil|round|pow|hypot|PI|sin|cos|tan|atan2?|Math)$/i;
const MATH_OPS = new Set(['*', '/', '%', '**']);
const BOUNDARY_IDS = new Set(['length', 'size', 'min', 'max', 'limit', 'count', 'index', 'offset', 'capacity', 'floor', 'ceil', 'round']);
const API_IDS = new Set(['export', 'interface', 'type', 'enum', 'default', 'return', 'declare']);

const FAILURE_MODES = {
  authz: 'Hypothesis: access-control or credential handling may now permit or deny the wrong principal.',
  boundary: 'Hypothesis: off-by-one or inclusive/exclusive handling may differ at equality, zero, empty or limit values.',
  math_spatial: 'Hypothesis: arithmetic or geometric results may be wrong for negative, zero-size, touching or degenerate inputs.',
  error_path: 'Hypothesis: error propagation, exception type or failure cleanup may differ from the previous behavior.',
  async: 'Hypothesis: ordering, awaiting, rejection handling or timing of asynchronous work may have changed.',
  validation: 'Hypothesis: input validation or type guards may accept invalid input or reject valid input.',
  state: 'Hypothesis: mutated or cached state may leak between calls or be updated in the wrong order.',
  conditional: 'Hypothesis: a branch condition may select the wrong path for some inputs.',
  api_contract: 'Hypothesis: the observable return value, signature or export contract may differ from callers\' expectations.',
  string_literal: 'Hypothesis: a changed literal (message, key, path or format) may break consumers that depend on its exact text.',
  data_literal: 'Hypothesis: a changed numeric or literal constant may alter computed results.',
  logic_change: 'Hypothesis: renamed or restructured logic may have changed behavior in an unexpected way.',
};

const RULESET_DESCRIPTOR = {
  id: 'atd.risk-rules/1',
  weights: WEIGHTS,
  levels: { high: 5, medium: 3 },
  patterns: {
    authz: AUTHZ_RE.source, validation: VALIDATION_RE.source, math: MATH_RE.source, errorChanged: ERROR_CHANGED_RE.source,
  },
  sets: {
    relational: [...RELATIONAL].sort(), conditionalKeywords: [...CONDITIONAL_KEYWORDS].sort(), conditionalOps: [...CONDITIONAL_OPS].sort(),
    async: [...ASYNC_IDS].sort(), errorContext: [...ERROR_CONTEXT_IDS].sort(), state: [...STATE_IDS].sort(), assign: [...ASSIGN_OPS].sort(),
    mathOps: [...MATH_OPS].sort(), boundary: [...BOUNDARY_IDS].sort(), api: [...API_IDS].sort(),
  },
  limits: { maxSourceBytes: MAX_SOURCE_BYTES, maxHunksPerFile: MAX_HUNKS_PER_FILE, maxBehaviorsPerFile: MAX_BEHAVIORS_PER_FILE },
  failureModes: FAILURE_MODES,
};
export const RULESET = { id: RULESET_DESCRIPTOR.id, sha256: canonicalSha256(RULESET_DESCRIPTOR) };

// ---------------------------------------------------------------------------
// git diff plumbing
// ---------------------------------------------------------------------------
export const DIFF_FLAGS = ['--no-color', '--no-ext-diff', '--no-textconv', '--no-renames'];

function parseRawDiff(buf) {
  const parts = buf.toString('utf8').split('\0');
  const entries = [];
  for (let i = 0; i + 1 < parts.length; i += 2) {
    const meta = parts[i];
    const file = parts[i + 1];
    if (!meta.startsWith(':')) continue;
    const f = meta.slice(1).split(' ');
    entries.push({ oldMode: f[0], newMode: f[1], oldSha: f[2], newSha: f[3], status: f[4][0], file });
  }
  return entries;
}

function binaryFiles(buf) {
  const out = new Set();
  const parts = buf.toString('utf8').split('\0');
  for (const part of parts) {
    const m = /^(-|\d+)\t(-|\d+)\t(.*)$/s.exec(part);
    if (m && m[1] === '-' && m[2] === '-') out.add(m[3]);
  }
  return out;
}

function lineHunks(repository, base, candidate, file) {
  const out = git(repository, ['diff', ...DIFF_FLAGS, '-U0', base, candidate, '--', file]).toString('utf8');
  const ranges = [];
  for (const line of out.split('\n')) {
    const m = /^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@/.exec(line);
    if (!m) continue;
    const start = Number(m[1]);
    const len = m[2] === undefined ? 1 : Number(m[2]);
    ranges.push(len === 0 ? { startLine: Math.max(start, 1), endLine: Math.max(start, 1) } : { startLine: start, endLine: start + len - 1 });
  }
  return ranges;
}

function mergeRanges(ranges) {
  const sorted = [...ranges].sort((a, b) => a.startLine - b.startLine || a.endLine - b.endLine);
  const out = [];
  for (const r of sorted) {
    const last = out[out.length - 1];
    if (last && r.startLine <= last.endLine + 1) last.endLine = Math.max(last.endLine, r.endLine);
    else out.push({ startLine: r.startLine, endLine: r.endLine });
  }
  while (out.length > MAX_HUNKS_PER_FILE) {
    let best = 0;
    let gap = Infinity;
    for (let i = 0; i + 1 < out.length; i++) {
      const g = out[i + 1].startLine - out[i].endLine;
      if (g < gap) { gap = g; best = i; }
    }
    out.splice(best, 2, { startLine: out[best].startLine, endLine: out[best + 1].endLine });
  }
  return out;
}

// ---------------------------------------------------------------------------
// File classification
// ---------------------------------------------------------------------------
function skipReasonForPath(entry, binary) {
  const { file } = entry;
  if (entry.status === 'D') return 'deleted';
  if (binary.has(file)) return 'binary';
  const segments = file.split('/');
  if (segments.slice(0, -1).some((s) => DEPENDENCY_DIRS.has(s))) return 'dependency_dir';
  if (LOCKFILES.has(segments[segments.length - 1])) return 'lockfile';
  if (GENERATED_NAME_RE.test(file)) return 'generated';
  if (entry.status === 'T' || entry.newMode === '160000' || entry.newMode === '120000') return 'non_source';
  if (!sourceExtension(file) || isTestPath(file) || CONFIG_NAME_RE.test(file)) return 'non_source';
  return null;
}

function hasGeneratedHeader(text) {
  return GENERATED_HEADER_RE.test(text.split('\n').slice(0, 20).join('\n'));
}

// ---------------------------------------------------------------------------
// Rule detection
// ---------------------------------------------------------------------------
function shorten(text, max) {
  const flat = text.replace(/\s+/g, ' ').trim();
  return flat.length > max ? `${flat.slice(0, max - 1)}…` : flat;
}

function tokenText(tokens) {
  return tokens.map((t) => t.raw).join(' ');
}

function detectRules({ changed, removed, context, inParams }) {
  const all = [...changed, ...removed];
  const ids = (list) => list.filter((t) => t.t === 'id').map((t) => t.v);
  const ops = (list) => list.filter((t) => t.t === 'p').map((t) => t.v);
  const changedIds = ids(all);
  const changedOps = ops(all);
  const ctxIds = ids(context);
  const ctxOps = ops(context);
  const rules = new Set();

  if (all.some((t) => t.t === 'str' || t.t === 'tpl')) rules.add('string_literal');
  if (all.some((t) => t.t === 'num' || t.t === 're')) rules.add('data_literal');
  if (all.some((t) => t.t === 're')) rules.add('validation');
  if (changedOps.some((o) => RELATIONAL.has(o)) || all.some((t) => t.t === 'num') || changedIds.some((v) => BOUNDARY_IDS.has(v))) rules.add('boundary');
  if (changedIds.some((v) => CONDITIONAL_KEYWORDS.has(v)) || changedOps.some((o) => CONDITIONAL_OPS.has(o))) rules.add('conditional');
  if (changedIds.some((v) => ASYNC_IDS.has(v))) rules.add('async');
  if (changedIds.some((v) => ERROR_CHANGED_RE.test(v)) || (ctxIds.some((v) => ERROR_CONTEXT_IDS.has(v)))) rules.add('error_path');
  const memberAssign = context.some((t, i) => t.t === 'p' && ASSIGN_OPS.has(t.v) && i >= 2 && context[i - 1].t === 'id' && context[i - 2].t === 'p' && context[i - 2].v === '.');
  if (changedIds.some((v) => STATE_IDS.has(v)) || changedOps.some((o) => o === '++' || o === '--') || (memberAssign && all.length > 0)) rules.add('state');
  if (ctxIds.some((v) => AUTHZ_RE.test(v)) || all.some((t) => t.t === 'str' && AUTHZ_RE.test(t.v))) rules.add('authz');
  if (ctxIds.some((v) => VALIDATION_RE.test(v)) && (changedIds.length + changedOps.length) > 0) rules.add('validation');
  if (ctxIds.some((v) => MATH_RE.test(v)) || changedOps.some((o) => MATH_OPS.has(o)) || ctxOps.some((o) => MATH_OPS.has(o) && changedOps.length > 0)) rules.add('math_spatial');
  if (inParams || changedIds.some((v) => API_IDS.has(v))) rules.add('api_contract');
  if (rules.size === 0) rules.add('logic_change');
  return [...rules].sort();
}

function riskLevel(ruleIds, lineCount) {
  const score = ruleIds.reduce((sum, r) => sum + (WEIGHTS[r] || 0), 0) + (lineCount > 40 ? 1 : 0);
  if (score >= RULESET_DESCRIPTOR.levels.high) return 'high';
  if (score >= RULESET_DESCRIPTOR.levels.medium) return 'medium';
  return 'low';
}

// ---------------------------------------------------------------------------
// Per-file analysis
// ---------------------------------------------------------------------------
function analyzeFile({ repository, baseCommit, candidateCommit, entry, baseText, candText }) {
  const candLex = lex(candText);
  const baseLex = baseText === '' ? { tokens: [], ok: true } : lex(baseText);
  const lineCount = Math.max(1, candText.split(/\r\n|[\n\r\u2028\u2029]/).length - (/[\n\r]$/.test(candText) ? 1 : 0));

  if (!candLex.ok || !baseLex.ok) {
    // Conservative: lexical doubt means every textual hunk is meaningful.
    const ranges = mergeRanges(lineHunks(repository, baseCommit, candidateCommit, entry.file)).map((r) => ({ startLine: r.startLine, endLine: Math.min(r.endLine, lineCount) }));
    if (ranges.length === 0) return null;
    const ruleIds = ['logic_change'];
    return {
      file: entry.file,
      symbols: ['<module>'],
      riskLevel: riskLevel(ruleIds, ranges.reduce((n, r) => n + r.endLine - r.startLine + 1, 0)),
      changedBehaviors: [`Textual change in ${ranges.length} range(s); token analysis unavailable (lexical doubt), treated as meaningful`],
      suspectedFailureModes: [FAILURE_MODES.logic_change],
      affectedTests: [],
      confidence: 0.5,
      hunks: ranges,
      ruleIds,
      symbolRanges: [],
    };
  }

  const baseKept = comparableTokens(baseLex.tokens);
  const candKept = comparableTokens(candLex.tokens);
  const groups = diffKeys(baseKept.map((k) => k.key), candKept.map((k) => k.key));
  if (groups.length === 0) return null; // formatting_only

  const symbols = extractSymbols(candLex.tokens);
  const ranges = [];
  const changedCand = [];
  const removedBase = [];
  const hitSymbols = new Map();
  const behaviors = [];
  let inParams = false;

  const symbolKey = (s) => `${s.name}|${s.startLine}|${s.endLine}`;
  for (const g of groups) {
    const added = candKept.slice(g.b0, g.b1).map((k) => k.tok);
    const removed = baseKept.slice(g.a0, g.a1).map((k) => k.tok);
    for (const t of added) changedCand.push(t);
    for (const t of removed) removedBase.push(t);
    let t0;
    let t1;
    let lo;
    let hi;
    if (added.length > 0) {
      t0 = candKept[g.b0].index;
      t1 = candKept[g.b1 - 1].index;
      lo = added[0].l;
      hi = added[added.length - 1].el;
    } else {
      const prev = g.b0 > 0 ? candKept[g.b0 - 1] : null;
      const next = g.b0 < candKept.length ? candKept[g.b0] : null;
      if (!prev && !next) continue;
      t0 = next ? next.index : prev.index;
      t1 = t0;
      lo = prev ? prev.tok.el : next.tok.l;
      hi = next ? next.tok.l : prev.tok.el;
      if (hi < lo) hi = lo;
    }
    ranges.push({ startLine: lo, endLine: hi });

    const touched = symbols.filter((s) => s.startTok <= t1 && s.endTok >= t0);
    const chosen = touched.filter((s) => !touched.some((c) => c !== s && c.startTok >= s.startTok && c.endTok <= s.endTok
      && (c.startTok !== s.startTok || c.endTok !== s.endTok)
      && c.startTok <= Math.max(t0, s.startTok) && c.endTok >= Math.min(t1, s.endTok)));
    const spans = touched.map((s) => [s.startTok, s.endTok]).sort((a, b) => a[0] - b[0]);
    let covered = t0;
    for (const [a, b] of spans) {
      if (a > covered) break;
      covered = Math.max(covered, b + 1);
    }
    const uncovered = covered <= t1;
    for (const s of chosen) {
      hitSymbols.set(symbolKey(s), s);
      if (s.params && t0 <= s.params.e && t1 >= s.params.s) inParams = true;
    }
    const label = chosen.length > 0 ? chosen.map((s) => s.name).join(', ') : '<module>';
    if (uncovered || chosen.length === 0) hitSymbols.set('<module>', { name: '<module>' });
    if (behaviors.length < MAX_BEHAVIORS_PER_FILE) {
      const where = `${label} (line ${lo}${hi > lo ? `-${hi}` : ''})`;
      if (removed.length > 0 && added.length > 0) behaviors.push(`${where}: replaced \`${shorten(tokenText(removed), 80)}\` with \`${shorten(tokenText(added), 80)}\``);
      else if (added.length > 0) behaviors.push(`${where}: added \`${shorten(tokenText(added), 80)}\``);
      else behaviors.push(`${where}: removed \`${shorten(tokenText(removed), 80)}\``);
    }
  }
  if (ranges.length === 0) return null;

  const hunks = mergeRanges(ranges).map((r) => ({ startLine: r.startLine, endLine: Math.min(r.endLine, lineCount) }));
  const context = candLex.tokens.filter((t) => hunks.some((r) => t.el >= r.startLine && t.l <= r.endLine));
  const ruleIds = detectRules({ changed: changedCand, removed: removedBase, context, inParams });
  const symbolNames = [...new Set([...hitSymbols.values()].map((s) => s.name))].sort();
  const symbolRanges = [...hitSymbols.values()].filter((s) => s.name !== '<module>')
    .map((s) => ({ name: s.name, startLine: s.startLine, endLine: s.endLine }))
    .sort((a, b) => a.startLine - b.startLine || (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  const hunkLines = hunks.reduce((n, r) => n + r.endLine - r.startLine + 1, 0);
  return {
    file: entry.file,
    symbols: symbolNames,
    riskLevel: riskLevel(ruleIds, hunkLines),
    changedBehaviors: behaviors,
    suspectedFailureModes: ruleIds.map((r) => FAILURE_MODES[r]),
    affectedTests: [],
    confidence: 0.9,
    hunks,
    ruleIds,
    symbolRanges,
  };
}

// ---------------------------------------------------------------------------
// Affected tests
// ---------------------------------------------------------------------------
const stripExt = (p) => p.replace(/\.(?:[cm]?[jt]sx?)$/, '');

export function listTestFiles(repository, commit) {
  const out = git(repository, ['ls-tree', '-r', '-z', '--name-only', commit]).toString('utf8').split('\0').filter(Boolean);
  return out.filter((f) => sourceExtension(f) && isTestPath(f)).sort().slice(0, MAX_TEST_FILES);
}

/** Maps target file -> sorted list of existing test files that import it or share its stem. */
export function findAffectedTests({ repository, candidateCommit, targetFiles, existingTests }) {
  let candidates;
  if (existingTests === undefined || existingTests === null) candidates = listTestFiles(repository, candidateCommit);
  else {
    if (!Array.isArray(existingTests) || existingTests.length > MAX_EXISTING_TESTS || existingTests.some((t) => typeof t !== 'string')) {
      throw new DiscoveryError('invalid_tests', `existingTests must be an array of at most ${MAX_EXISTING_TESTS} repository-relative paths`);
    }
    candidates = [...new Set(existingTests)].sort();
  }
  const result = new Map(targetFiles.map((f) => [f, new Set()]));
  const wanted = new Map(targetFiles.map((f) => [f, stripExt(f)]));
  for (const test of candidates) {
    if (test.includes('\0') || test.startsWith('/') || test.split('/').includes('..')) {
      throw new DiscoveryError('invalid_tests', `unsafe existing test path ${JSON.stringify(test)}`);
    }
    const blob = readBlob(repository, candidateCommit, test);
    if (!blob || blob.length > MAX_TEST_BYTES) continue;
    const lexed = lex(blob.toString('utf8'));
    const dir = path.posix.dirname(test);
    const resolved = new Set();
    if (lexed.ok) {
      for (const spec of moduleSpecifiers(lexed.tokens)) {
        if (!spec.specifier || !spec.specifier.startsWith('.')) continue;
        const target = stripExt(path.posix.normalize(path.posix.join(dir, spec.specifier)));
        resolved.add(target);
        resolved.add(`${target}/index`);
      }
    }
    const stem = stripExt(path.posix.basename(test).replace(/\.(?:test|spec)(?=\.)/, ''));
    for (const [file, noExt] of wanted) {
      const fileStem = path.posix.basename(noExt);
      const isIndex = fileStem === 'index';
      if (resolved.has(noExt) || (isIndex && resolved.has(path.posix.dirname(noExt))) || stem === fileStem) result.get(file).add(test);
    }
  }
  return new Map([...result].map(([k, v]) => [k, [...v].sort()]));
}

