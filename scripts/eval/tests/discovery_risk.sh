#!/usr/bin/env bash
# Consumer-visible behavior of scripts/eval/discovery/risk.mjs (atd.change-risk/v1):
# relevant changes become targets with exact provenance, ranges, symbols and affected tests;
# formatting/comment-only, generated, dependency, lockfile, deleted, binary and non-source changes
# produce no target (with a recorded reason); string/regex/template literal changes stay targets.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/../lib/portable.sh"
RISK="$SCRIPT_DIR/../discovery/risk.mjs"

command -v node >/dev/null 2>&1 || { echo "SKIP: node not available" >&2; exit 0; }
command -v git >/dev/null 2>&1 || { echo "SKIP: git not available" >&2; exit 0; }

WORK="$(mktemp -d -t eval-harness-risk.XXXXXX)"
trap 'rm -rf "$WORK"' EXIT
REPO="$WORK/repo"

fail() { echo "FAIL: $*" >&2; exit 1; }
export GIT_AUTHOR_NAME=t GIT_AUTHOR_EMAIL=t@example.com GIT_COMMITTER_NAME=t GIT_COMMITTER_EMAIL=t@example.com
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_NOSYSTEM=1

g() { git -C "$REPO" -c commit.gpgsign=false -c core.autocrlf=false "$@"; }
sha256_of() { portable_sha256_file "$1" | cut -d' ' -f1; }
check() { # report-name jq-expression message
  jq -e "$2" "$WORK/$1.json" >/dev/null || { echo "report $1:" >&2; cat "$WORK/$1.json" >&2; fail "$3"; }
}
analyze() { # candidate-sha name [extra risk.mjs args]
  local cand="$1" name="$2"; shift 2
  node "$RISK" --repo="$REPO" --base="$BASE" --candidate="$cand" --out="$WORK/$name.json" "$@" \
    || fail "risk.mjs exited nonzero for $name"
}
variant() { g checkout -q -B "$1" "$BASE"; }
replace_in() { # file old new (literal, line-based)
  awk -v old="$2" -v new="$3" '{ out = ""; rest = $0; while ((i = index(rest, old)) > 0) { out = out substr(rest, 1, i - 1) new; rest = substr(rest, i + length(old)) } print out rest }' "$1" > "$1.tmp" && mv "$1.tmp" "$1"
}
commit_variant() { g add -A -f; g commit -q -m "$1"; g rev-parse HEAD; }
write_asi() { # early-return-text directive postfix-first-line postfix-second-line
  cat > "$REPO/src/asi.js" <<ASI
export function early(flag) {
  $1
}
export function strictThis() {
  $2
  return this === undefined;
}
export function bump(a, b) {
  $3
  $4
  return [a, b];
}
ASI
}

# --------------------------------------------------------------------------- fixture
mkdir -p "$REPO/src" "$REPO/test" "$REPO/node_modules/dep" "$REPO/dist" "$REPO/assets"
g init -q
cat > "$REPO/src/collision.ts" <<'EOF'
export interface Rect {
  x: number;
  y: number;
  width: number;
  height: number;
}

/** Axis-aligned overlap. Touching edges are not an overlap. */
export function overlaps(a: Rect, b: Rect): boolean {
  return a.x < b.x + b.width && a.x + a.width > b.x && a.y < b.y + b.height && a.y + a.height > b.y;
}

export const MESSAGE = 'no overlap';

export const label = (a: Rect, b: Rect): string => (overlaps(a, b) ? 'overlap' : MESSAGE);
EOF
cat > "$REPO/src/other.ts" <<'EOF'
export const other = 1;
EOF
cat > "$REPO/src/util.js" <<'EOF'
export function add(a, b) {
  // sum
  return a + b;
}
EOF
cat > "$REPO/src/validate.js" <<'EOF'
export function isCode(s) {
  const re = /^ab+c$/;
  return re.test(s);
}
export const URL_BASE = 'http://example.com/a /* not a comment */';
export function sum(a, b) {
  return `sum=${a + b}`;
}
EOF
cat > "$REPO/test/collision.test.ts" <<'EOF'
import { describe, expect, it } from 'vitest';
import { overlaps } from '../src/collision';

describe('overlaps', () => {
  it('detects overlap', () => {
    expect(overlaps({ x: 0, y: 0, width: 2, height: 2 }, { x: 1, y: 1, width: 2, height: 2 })).toBe(true);
  });
});
EOF
cat > "$REPO/test/unrelated.test.ts" <<'EOF'
import { expect, it } from 'vitest';
import { other } from '../src/other';

it('other is one', () => {
  expect(other).toBe(1);
});
EOF
printf '{"name":"fixture","type":"module","devDependencies":{"vitest":"^2.0.0"}}\n' > "$REPO/package.json"
printf '{"lockfileVersion":3}\n' > "$REPO/package-lock.json"
printf '# Fixture\n' > "$REPO/README.md"
printf 'module.exports = 1;\n' > "$REPO/node_modules/dep/index.js"
printf 'var bundle = 1;\n' > "$REPO/dist/bundle.js"
printf '// @generated by fixture-tool\nexport const A = 1;\n' > "$REPO/src/schema.ts"
printf '\x89PNG\r\n\x1a\n\0\0\0\rIHDR' > "$REPO/assets/logo.png"
write_asi 'return flag;' '"use strict";' 'a' '++b;'
g add -A -f
g commit -q -m base
BASE="$(g rev-parse HEAD)"
[[ "$BASE" =~ ^[0-9a-f]{40}$ ]] || fail "fixture base SHA invalid"
printf 'Rectangles that merely touch along an edge do not overlap.\n' > "$WORK/spec.md"

# --------------------------------------------------------------------------- 1. boundary change is a target
variant boundary
replace_in "$REPO/src/collision.ts" 'a.x < b.x + b.width' 'a.x <= b.x + b.width'
BOUNDARY="$(commit_variant boundary)"
analyze "$BOUNDARY" boundary --spec="$WORK/spec.md"
RET_LINE="$(grep -n 'return a.x' "$REPO/src/collision.ts" | cut -d: -f1)"
check boundary '.schema == "atd.change-risk/v1"' "schema id"
check boundary ".baseCommit == \"$BASE\" and .candidateCommit == \"$BOUNDARY\"" "full-SHA revision provenance"
check boundary '.diffSha256 | test("^[0-9a-f]{64}$")' "diff hash"
check boundary ".specSha256 == \"$(sha256_of "$WORK/spec.md")\"" "spec hash binds the supplied bytes"
check boundary '.ruleset.sha256 | test("^[0-9a-f]{64}$")' "ruleset hash"
check boundary '.llmAssist.used == false' "deterministic report records no LLM assist"
check boundary '(.targets | length) == 1 and .targets[0].file == "src/collision.ts"' "exactly one relevant target"
check boundary '.targets[0].symbols | index("overlaps") != null' "changed symbol overlaps"
check boundary ".targets[0].hunks | any(.startLine <= $RET_LINE and .endLine >= $RET_LINE)" "hunk covers the changed return line"
check boundary '.targets[0].ruleIds | (index("boundary") != null) and (index("conditional") != null)' "boundary and conditional rules"
check boundary '.targets[0].riskLevel == "high"' "risk level high for a spatial boundary change"
check boundary '.targets[0].changedBehaviors | join(" ") | contains("`<=`")' "changed behavior names the new operator"
check boundary '.targets[0].suspectedFailureModes | length > 0 and all(startswith("Hypothesis"))' "failure modes are labelled hypotheses"
check boundary '.targets[0].affectedTests == ["test/collision.test.ts"]' "only the importing test is affected"
check boundary '.targets[0].symbolRanges | any(.name == "overlaps")' "function range recorded"
check boundary '(.skipped | length) == 0' "nothing skipped"

# --------------------------------------------------------------------------- 2. deterministic output
analyze "$BOUNDARY" boundary2 --spec="$WORK/spec.md"
cmp -s "$WORK/boundary.json" "$WORK/boundary2.json" || fail "report is not byte-identical across runs"
analyze "$BOUNDARY" nospec
check nospec '.specSha256 == null' "no spec => null specSha256"

# --------------------------------------------------------------------------- 3. formatting-only yields no targets
variant formatting
cat > "$REPO/src/collision.ts" <<'EOF'
export interface Rect {
    x: number;
    y: number;
    width: number;
    height: number;
}

// Axis-aligned overlap.
// Touching edges are not an overlap (comment reworded).
export function overlaps(a: Rect, b: Rect): boolean {
    return (
        a.x < b.x + b.width &&
        a.x + a.width > b.x &&
        a.y < b.y + b.height &&
        a.y + a.height > b.y
    );
}

export const MESSAGE = "no overlap";

export const label = (a: Rect, b: Rect): string => (
    overlaps(a, b) ? "overlap" : MESSAGE
);
EOF
FORMATTING="$(commit_variant formatting)"
analyze "$FORMATTING" formatting
check formatting '.targets == []' "formatting-only change must not yield targets"
check formatting '.skipped == [{"file":"src/collision.ts","reason":"formatting_only"}]' "formatting-only reason recorded"

variant crlf
awk '{printf "%s\r\n", $0}' "$REPO/src/collision.ts" > "$WORK/crlf.ts"
cp "$WORK/crlf.ts" "$REPO/src/collision.ts"
CRLF="$(commit_variant crlf)"
analyze "$CRLF" crlf
check crlf '.targets == [] and (.skipped | map(.reason) == ["formatting_only"])' "line-ending change is formatting only"

variant comments
cat > "$REPO/src/util.js" <<'EOF'
/**
 * Adds two numbers.
 */
export function add(a, b) {
  // sum of both operands, reworded
  /* block comment */
  return a + b;
}
EOF
COMMENTS="$(commit_variant comments)"
analyze "$COMMENTS" comments
check comments '.targets == [] and .skipped == [{"file":"src/util.js","reason":"formatting_only"}]' "comment-only change yields no target"

# --------------------------------------------------------------------------- 4. meaningful literal changes stay targets
variant string
replace_in "$REPO/src/collision.ts" "'no overlap'" "'separate'"
STRING="$(commit_variant string)"
analyze "$STRING" string
check string '(.targets | length) == 1 and (.targets[0].ruleIds | index("string_literal") != null)' "string literal change is a target"
check string '.targets[0].symbols == ["<module>"]' "top-level literal is attributed to the module"
check string '.skipped == []' "string change is not skipped"

variant literals
cat > "$REPO/src/validate.js" <<'EOF'
export function isCode(s) {
  const re = /^ab+d$/;
  return re.test(s);
}
export const URL_BASE = 'http://example.com/b /* not a comment */';
export function sum(a, b) {
  return `sum=${a - b}`;
}
EOF
LITERALS="$(commit_variant literals)"
analyze "$LITERALS" literals
check literals '.targets | length == 1 and .[0].file == "src/validate.js"' "regex, URL-with-// string and template expression changes are targets"
check literals '.targets[0].hunks | length == 3' "three separate literal hunks"
check literals '.targets[0].symbols | (index("isCode") != null) and (index("sum") != null) and (index("<module>") != null)' "literal changes attributed to their symbols"

variant quotes
cat > "$REPO/src/validate.js" <<'EOF'
export function isCode(s) {
  const re = /^ab+c$/;
  return re.test(s);
}
export const URL_BASE = "http://example.com/a /* not a comment */";
export function sum(a, b) {
  return `sum=${a + b}`;
}
EOF
QUOTES="$(commit_variant quotes)"
analyze "$QUOTES" quotes
check quotes '.targets == [] and .skipped[0].reason == "formatting_only"' "quote style change keeps literal semantics and is formatting only"

# --------------------------------------------------------------------------- 4b. newline / escape semantics are never "formatting"
# `return\nx` returns undefined, `a\n++b` is `a; ++b`, and "\x75se strict" is not a directive: each differs in behavior.
asi_target() { # name sha expected-symbol
  analyze "$2" "$1"
  check "$1" ".targets | length == 1 and .[0].file == \"src/asi.js\" and (.[0].symbols | index(\"$3\") != null)" "$1: behavior-changing newline/escape change must be a target"
  check "$1" '.skipped == []' "$1: not skipped"
}
asi_ignored() { # name sha
  analyze "$2" "$1"
  check "$1" '.targets == [] and .skipped == [{"file":"src/asi.js","reason":"formatting_only"}]' "$1: semantics-preserving reformatting must stay formatting only"
}
variant asi-return
write_asi $'return\n  flag;' '"use strict";' 'a' '++b;'
asi_target asi-return "$(commit_variant asi-return)" early
variant asi-escape
write_asi 'return flag;' '"\x75se strict";' 'a' '++b;'
asi_target asi-escape "$(commit_variant asi-escape)" strictThis
variant asi-postfix
write_asi 'return flag;' '"use strict";' 'a++' 'b;'
asi_target asi-postfix "$(commit_variant asi-postfix)" bump
variant asi-restricted-paren
write_asi $'return\n  (flag);' '"use strict";' 'a' '++b;'
asi_target asi-restricted-paren "$(commit_variant asi-restricted-paren)" early
variant asi-quote
write_asi 'return flag;' "'use strict';" 'a' '++b;'
asi_ignored asi-quote "$(commit_variant asi-quote)"
variant asi-paren
write_asi $'return (\n    flag\n  );' '"use strict";' 'a' '++b;'
asi_ignored asi-paren "$(commit_variant asi-paren)"
variant asi-space
write_asi 'return    flag ;' '"use strict" ;' 'a' '++b ;'
asi_ignored asi-space "$(commit_variant asi-space)"
# `(a, b) => (a, b)` returns b; `(a, b) => a, b` returns a: removing the parentheses is a behavior change
variant arrow-comma
printf 'export let pair = (a, b) => (a, b);\n' > "$REPO/src/arrow.js"
g add -A -f; g commit -q -m arrow-base
ARROW_BASE="$(g rev-parse HEAD)"
printf 'export let pair = (a, b) => a, b;\n' > "$REPO/src/arrow.js"
g add -A -f; g commit -q -m arrow-comma
node "$RISK" --repo="$REPO" --base="$ARROW_BASE" --candidate="$(g rev-parse HEAD)" --out="$WORK/arrow-comma.json" \
  || fail "risk.mjs exited nonzero for arrow-comma"
check arrow-comma '.targets | length == 1 and .[0].file == "src/arrow.js"' "removing parentheses around a comma arrow body changes behavior and must be a target"

# --------------------------------------------------------------------------- 5. deletion-only and new file
variant deletion
replace_in "$REPO/src/collision.ts" ' && a.y + a.height > b.y;' ';'
DELETION="$(commit_variant deletion)"
analyze "$DELETION" deletion
check deletion '.targets | length == 1 and (.[0].symbols | index("overlaps") != null)' "deleting a condition clause is a target in its function"
check deletion '.targets[0].changedBehaviors | join(" ") | contains("removed")' "removal described"

variant newfile
printf 'export function double(n) {\n  return n * 2;\n}\n' > "$REPO/src/new.js"
NEWFILE="$(commit_variant newfile)"
analyze "$NEWFILE" newfile
check newfile '.targets | length == 1 and .[0].file == "src/new.js" and .[0].hunks == [{"startLine":1,"endLine":3}]' "new source file is one whole-file hunk"
check newfile '.targets[0].symbols == ["double"]' "new function recorded"

# --------------------------------------------------------------------------- 6. skipped categories
variant skips
printf '{"lockfileVersion":4}\n' > "$REPO/package-lock.json"
printf 'module.exports = 2;\n' > "$REPO/node_modules/dep/index.js"
printf 'var bundle = 2;\n' > "$REPO/dist/bundle.js"
printf '// @generated by fixture-tool\nexport const A = 2;\n' > "$REPO/src/schema.ts"
printf '# Fixture\n\nMore docs.\n' > "$REPO/README.md"
printf '\x89PNG\r\n\x1a\n\0\0\0\rIDAT' > "$REPO/assets/logo.png"
rm "$REPO/src/other.ts"
printf "import { expect, it } from 'vitest';\nit('x', () => { expect(1).toBe(1); });\n" > "$REPO/test/new.test.ts"
SKIPS="$(commit_variant skips)"
analyze "$SKIPS" skips
check skips '.targets == []' "dependency/lock/generated/docs/binary/deleted/test changes yield no targets"
check skips '[.skipped[] | {(.file): .reason}] | add == {
  "README.md":"non_source", "assets/logo.png":"binary", "dist/bundle.js":"dependency_dir",
  "node_modules/dep/index.js":"dependency_dir", "package-lock.json":"lockfile", "src/other.ts":"deleted",
  "src/schema.ts":"generated", "test/new.test.ts":"non_source"}' "every skipped file records its reason"

# --------------------------------------------------------------------------- 7. mixed change keeps only the relevant file
variant mixed
printf 'export function add(a, b) {\n    return (a + b);\n}\n' > "$REPO/src/util.js"
replace_in "$REPO/src/collision.ts" 'a.x < b.x + b.width' 'a.x <= b.x + b.width'
MIXED="$(commit_variant mixed)"
analyze "$MIXED" mixed
check mixed '(.targets | map(.file)) == ["src/collision.ts"] and .skipped == [{"file":"src/util.js","reason":"formatting_only"}]' "formatting-only file skipped while the real change is targeted"

# --------------------------------------------------------------------------- 8. affected tests and API
analyze "$BOUNDARY" unrelated-only --tests=test/unrelated.test.ts
check unrelated-only '.targets[0].affectedTests == []' "explicit existingTests restricts affected tests"
analyze "$BOUNDARY" collision-only --tests=test/collision.test.ts,test/unrelated.test.ts
check collision-only '.targets[0].affectedTests == ["test/collision.test.ts"]' "unrelated tests are not affected"

OUT="$(cd "$REPO" && node --input-type=module -e '
const { analyzeChange } = await import(process.argv[1]);
const r = analyzeChange({ repository: process.argv[2], baseCommit: process.argv[3], candidateCommit: process.argv[4], spec: { text: "Rectangles that merely touch along an edge do not overlap.\n" }, existingTests: ["test/collision.test.ts"] });
console.log(JSON.stringify({ spec: r.specSha256, tests: r.targets[0].affectedTests, file: r.targets[0].file }));
' "file://$(cd "$SCRIPT_DIR/../discovery" && pwd)/risk.mjs" "$REPO" "$BASE" "$BOUNDARY")" || fail "programmatic analyzeChange failed"
[[ "$(jq -r .spec <<<"$OUT")" == "$(sha256_of "$WORK/spec.md")" ]] || fail "programmatic spec text hash differs from file hash"
[[ "$(jq -r '.tests[0]' <<<"$OUT")" == "test/collision.test.ts" ]] || fail "programmatic existingTests ignored"

# --------------------------------------------------------------------------- 9. error handling and safety
if node "$RISK" --repo="$REPO" --base="--output=$WORK/pwned" --candidate="$BOUNDARY" --out="$WORK/x.json" 2>"$WORK/err.txt"; then
  fail "option-like revision must be rejected"
fi
grep -q 'invalid_revision' "$WORK/err.txt" || fail "option-like revision error not reported"
[[ ! -e "$WORK/pwned" ]] || fail "option injection created a file"
if node "$RISK" --repo="$REPO" --base=does-not-exist --candidate="$BOUNDARY" --out="$WORK/x.json" 2>/dev/null; then
  fail "unknown revision must fail"
fi
if node "$RISK" --repo="$REPO" --base="$BASE" --candidate="$BOUNDARY" --tests=../outside.test.ts --out="$WORK/x.json" 2>/dev/null; then
  fail "traversal in --tests must fail"
fi
set +e
node "$RISK" --repo="$REPO" >/dev/null 2>&1
[[ $? -eq 2 ]] || { echo "FAIL: missing required flags must exit 2" >&2; exit 1; }
node "$RISK" --help | grep -q 'atd.change-risk/v1' || { echo "FAIL: --help missing" >&2; exit 1; }
set -e
[[ ! -e "$WORK/x.json" ]] || fail "failed run wrote an output file"

[[ -z "$(g status --porcelain=v1)" ]] || fail "analysis left the repository dirty"

echo "PASS: change-risk — boundary/string/regex/template/deletion/new-file targets with exact provenance; formatting, comment, CRLF, quote-style, generated, dependency, lockfile, binary, deleted and non-source changes skipped with reasons; deterministic; option injection rejected"
exit 0
